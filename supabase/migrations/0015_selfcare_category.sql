-- ============================================================================
--  Категория «Самолюбование»
--
--  Спорт, фейсбилдинг, ванна. Время на себя.
--
--  ПОЧЕМУ БЕЗ СТАВКИ. Остальные категории отвечают на вопрос «сколько
--  стоило бы купить эту работу на стороне». Здесь вопрос не имеет
--  смысла: нанятый человек не может полежать в ванне вместо тебя.
--  Поэтому rate_id пусто — время считается, денежной оценки нет.
--
--  Это делает категорию заметно полезной в другом: на диаграмме сразу
--  видно, сколько времени в неделе достаётся себе. Ради такого вопроса
--  приложение и заводили.
-- ============================================================================

insert into public.categories (slug, name, icon, sort_order)
values ('selfcare', 'Самолюбование', '🌸', 6)
on conflict (slug) do nothing;

insert into public.subcategories (category_id, rate_id, name, sort_order)
select c.id, null, v.name, v.sort_order
from public.categories c
cross join (values
  ('Спорт',        1),
  ('Фейсбилдинг',  2),
  ('Приём ванны',  3)
) as v(name, sort_order)
where c.slug = 'selfcare'
  -- Повторный прогон миграции не должен плодить копии.
  and not exists (
    select 1 from public.subcategories s
    where s.category_id = c.id and s.name = v.name
  );
