-- ============================================================================
--  «Работа 1» и «Работа 2» получают человеческие имена
--
--    Работа 1 → Работа Andrei (инвест)
--    Работа 2 → Работа Andrei (epam)
--
--  ПОЧЕМУ. Номера пришли из приложения-источника, где часы лежат в полях
--  work1 и work2. Внутри программы это нормальный ключ, но в выпадающем
--  списке «Работа 1» не значит ничего: через полгода никто не вспомнит,
--  какая из них какая, и часы начнут попадать не туда.
--
--  Номера при этом НЕ исчезают — они остаются связью с приложением-
--  источником и записаны в src/features/earnings/workSources.ts.
--  Соответствие живёт в одном месте, чтобы переименование здесь
--  не разошлось с тем, что ждёт импорт.
--
--  Переименование безопасно для истории: записи ссылаются на строку
--  по её id, а не по названию, и ставка у каждой записи своя, замороженная.
-- ============================================================================

update public.market_rates
set name = 'Работа Andrei (инвест)'
where name = 'Работа 1 (net)';

update public.market_rates
set name = 'Работа Andrei (epam)'
where name = 'Работа 2 (net)';


update public.subcategories
set name = 'Работа Andrei (инвест)'
where name = 'Работа 1'
  and category_id = (select id from public.categories where slug = 'work');

update public.subcategories
set name = 'Работа Andrei (epam)'
where name = 'Работа 2'
  and category_id = (select id from public.categories where slug = 'work');
