-- ============================================================================
--  Пропуск одного повтора
--
--  Задачи из правил повтора Планер подставляет сам при каждом открытии
--  недели. Удалённая задача возвращалась: правило видело пустой день
--  и создавало её заново. «На этой неделе шахмат не было» записать
--  было нельзя.
--
--  Теперь такая задача не удаляется, а получает статус 'skipped'.
--  Строка остаётся, уникальный индекс (правило, дата) занят, и Планер
--  её больше не пересоздаёт. Остальные недели правило заполняет как
--  прежде. В статистику пропуск не попадает: она берёт только 'done'.
-- ============================================================================

alter table public.activities drop constraint activities_status_check;
alter table public.activities
  add constraint activities_status_check
    check (status in ('planned', 'done', 'skipped'));
