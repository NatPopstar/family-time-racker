-- ============================================================================
--  Исправление: подстановка повторяющихся задач падала с ошибкой 42P10
--
--  Симптом: правило создано, а задача в Планере не появлялась.
--  Сервер отвечал 400 с текстом
--      "there is no unique or exclusion constraint matching
--       the ON CONFLICT specification"
--
--  Причина: индекс из миграции 0004 был ЧАСТИЧНЫМ —
--      create unique index ... where recurring_rule_id is not null
--  PostgreSQL не умеет опираться на частичный индекс при ON CONFLICT,
--  если сам запрос не повторяет его условие WHERE. Supabase такое
--  условие не отправляет, поэтому база не находила подходящий индекс.
--
--  Решение: делаем индекс обычным, без условия. Это безопасно:
--  в уникальных индексах PostgreSQL считает NULL значения РАЗНЫМИ,
--  поэтому сколько угодно обычных задач (у них recurring_rule_id пустой)
--  спокойно уживаются в один и тот же день. Ограничение по-прежнему
--  работает только там, где правило указано.
-- ============================================================================

drop index if exists public.activities_rule_per_day_idx;

create unique index activities_rule_per_day_idx
  on public.activities (recurring_rule_id, date);
