-- ============================================================================
--  Категория «Администрирование» — работа личного помощника
--
--  Personal Assistant / Family Assistant, 25 €/час.
--
--  Это большой и почти невидимый пласт труда: заполнить форму, найти
--  мастера, сравнить цены, дозвониться в школу, отследить платёж.
--  Каждое дело мелкое, поэтому в конце дня кажется, что «ничего
--  не делала» — хотя ушли часы. Ради таких вещей приложение и писалось.
--
--  ПОЧЕМУ ОТДЕЛЬНАЯ КАТЕГОРИЯ, А НЕ ВНУТРИ «ДОМАШНИХ ОБЯЗАННОСТЕЙ».
--  Список выходит за рамки дома: поиск работы, документы ребёнка,
--  поездки. Отдельная категория сразу показывает свою долю на круговой
--  диаграмме — а спрятанная внутри быта она бы там растворилась.
--
--  ПОЧЕМУ ЧЕТЫРЕ ВИДА РАБОТЫ, А НЕ ЧЕТЫРНАДЦАТЬ.
--  Четырнадцать строк в выпадающем списке — это выбор, который делаешь
--  дольше, чем записываешь дело. Подробности и так попадают в название
--  записи: человек пишет «искала мастера, сравнила три цены, записалась
--  на четверг», и этого достаточно. Четыре группы отвечают на вопрос
--  «куда ушёл день», не мешая записывать.
-- ============================================================================

insert into public.categories (slug, name, icon, sort_order)
values ('admin', 'Администрирование', '📋', 5)
on conflict (slug) do nothing;

insert into public.market_rates (name, hourly_rate, currency)
values ('Personal Assistant / Family Assistant', 25, 'EUR')
on conflict (name) do update
  set hourly_rate = excluded.hourly_rate,
      currency    = excluded.currency;


-- ----------------------------------------------------------------------------
--  Четыре вида работы. В скобках — что из твоего списка сюда попадает.
--
--    1. Документы и формы
--       документы · семейная документация · онлайн-администрация
--    2. Поиск работы и отклики
--       поиск вакансий · отклики · карьерная администрация
--    3. Поиск и организация услуг
--       исследование · бытовые услуги · покупки и заказы · поездки
--    4. Переписка и организация
--       коммуникация · организация · финансовая администрация ·
--       общая координация семьи
-- ----------------------------------------------------------------------------
insert into public.subcategories (category_id, rate_id, name, sort_order)
select c.id, r.id, v.name, v.sort_order
from public.categories c
cross join public.market_rates r
cross join (values
  ('Документы и формы',        1),
  ('Поиск работы и отклики',   2),
  ('Поиск и организация услуг', 3),
  ('Переписка и организация',  4)
) as v(name, sort_order)
where c.slug = 'admin'
  and r.name = 'Personal Assistant / Family Assistant'
  -- Повторный прогон миграции не должен плодить копии.
  and not exists (
    select 1 from public.subcategories s
    where s.category_id = c.id and s.name = v.name
  );


-- ----------------------------------------------------------------------------
--  Разводим пересечение с «Покупками и организацией дома».
--
--  Оба про покупки, но труд разный: сходить в магазин и разобрать шкаф —
--  это ноги и руки (домработница, 23 €). Найти товар, сравнить цены,
--  оформить заказ и переписываться с продавцом — это экран (личный
--  помощник, 25 €). Пока граница не названа, одинаковые дела будут
--  попадать то туда, то сюда, и сравнивать месяцы станет нельзя.
--
--  Уже записанное НЕ трогаем: там всего несколько записей, и что именно
--  человек имел в виду, задним числом знать нельзя.
-- ----------------------------------------------------------------------------
update public.subcategories
set name = 'Покупки и хозяйство (ногами)'
where name = 'Покупки и организация дома'
  and category_id = (select id from public.categories where slug = 'household');
