-- ============================================================================
--  Французский язык и уточнённая школьная дорога
-- ============================================================================

-- Новый вид учёбы. Ставки нет: своя учёба рыночной оценки не имеет —
-- нанятый человек не выучит язык вместо тебя.
insert into public.subcategories (category_id, rate_id, name, sort_order)
select c.id, null, 'Французский язык', 6
from public.categories c
where c.slug = 'study'
  and not exists (
    select 1 from public.subcategories s
    where s.category_id = c.id and s.name = 'Французский язык'
  );


-- ----------------------------------------------------------------------------
--  Школьная дорога уточнена по факту.
--
--    отвести:  15 туда с ребёнком + 25 назад в гору без него = 40
--    забрать:  15 туда без ребёнка + 30 назад с ним          = 45
--
--  «Отвести» уже стоит верно (20 × 2 = 40). «Забрать» было 54 — это
--  считалось по прежним словам про 40 минут обратной дороги.
--
--  45 на два конца не делится, поэтому 22 × 2 = 44. Округляем ВНИЗ:
--  занижать оценку своего труда честнее, чем завышать. Минута в день.
-- ----------------------------------------------------------------------------
update public.recurring_rules
set travel_one_way_minutes = 22
where title = 'Забрать из школы';

-- Уже подставленные, но ещё НЕ выполненные задачи приводим в соответствие.
-- Выполненные не трогаем: там записано то, что случилось на самом деле.
update public.activities a
set travel_one_way_minutes = 22
from public.recurring_rules r
where r.id = a.recurring_rule_id
  and r.title = 'Забрать из школы'
  and a.status = 'planned';
