-- ============================================================================
--  Запланированные задачи — общие для родителей
--
--  Что меняется в правилах доступа.
--
--  БЫЛО: менять можно только свою запись; ничью — если ты взрослый.
--  Из-за этого задача «Отвести с Show lab», назначенная на Андрея,
--  была не видна и недоступна Наталье. Если по факту отвезла она,
--  отметить выполнение было нельзя.
--
--  СТАЛО: пока задача ЗАПЛАНИРОВАНА, любой взрослый может её взять,
--  изменить и отметить выполненной. Кто отметил — на того и записывается.
--
--  Почему именно так: запланированная задача это ДОГОВОРЁННОСТЬ семьи,
--  а не чья-то личная запись. Личной она становится в момент выполнения.
--  Поэтому ВЫПОЛНЕННУЮ запись по-прежнему может менять только её владелец:
--  это уже история его труда, и чужие руки в ней не нужны.
-- ============================================================================

drop policy "activities updatable" on public.activities;
drop policy "activities deletable" on public.activities;

create policy "activities updatable"
  on public.activities for update to authenticated
  using (
    -- своя запись — всегда
    auth.uid() = user_id
    -- либо запланированная задача семьи, и ты взрослый
    or (public.is_adult() and (user_id is null or status = 'planned'))
  );

create policy "activities deletable"
  on public.activities for delete to authenticated
  using (
    auth.uid() = user_id
    or (public.is_adult() and (user_id is null or status = 'planned'))
  );
