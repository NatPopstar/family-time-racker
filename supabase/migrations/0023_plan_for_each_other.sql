-- ============================================================================
--  Взрослый может ЗАПЛАНИРОВАТЬ задачу на другого взрослого
--
--  Планер при открытии недели сам подставляет задачи из правил повтора.
--  Правило «Плавание (забрать)» закреплено за Natalia, поэтому браузер
--  Andrei пытался создать запись на чужое имя. Прежняя политика разрешала
--  создавать только свои и ничьи записи, база отказывала, и падала вся
--  пачка целиком: у Andrei не появлялось НИ ОДНОЙ задачи из повторов,
--  а вместо этого вылезало «new row violates row-level security policy».
--
--  Разрешаем взрослому создавать ЗАПЛАНИРОВАННЫЕ задачи на другого.
--  Это то же самое, что уже разрешено политиками изменения и удаления:
--  чужую запланированную задачу взрослый и так может исправить или убрать.
--
--  Выполненные записи ('done') по-прежнему создаёт только сам человек:
--  чужое «я это сделал» приписать нельзя, иначе статистика перестала бы
--  быть свидетельством о собственном труде.
-- ============================================================================

drop policy "activities insertable" on public.activities;

create policy "activities insertable"
  on public.activities for insert to authenticated
  with check (
    auth.uid() = user_id
    or user_id is null
    or (public.is_adult() and status = 'planned')
  );
