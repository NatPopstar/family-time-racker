/**
 * ОТКУДА БЕРУТСЯ ЧАСЫ РАБОТЫ АНДРЕЯ.
 *
 * Часы ведутся в другом приложении, и там у двух работ нет названий —
 * только номера полей: work1 и work2. Для программы это нормальный ключ,
 * для человека — пустой звук. Поэтому в нашей базе они называются
 * «Работа Andrei (инвест)» и «Работа Andrei (epam)».
 *
 * Здесь записано соответствие между тем и другим — в ОДНОМ месте.
 * Без него связь существовала бы только в чьей-то памяти: кто-то
 * переименовал бы вид работы в настройках, импорт перестал бы находить
 * его по названию и молча создал бы дубль или не записал ничего.
 *
 * СТАВКИ ЗДЕСЬ НАМЕРЕННО НЕТ. Она живёт в таблице market_rates, как
 * у всех остальных видов работы, и меняется в настройках. Продублируй
 * её здесь — и однажды два числа разойдутся, а какое из них настоящее,
 * будет непонятно.
 *
 * Автоматического импорта пока нет: часы переносились вручную. Этот файл —
 * то, на что импорт обопрётся, когда появится.
 */

/** Как две работы называются в приложении-источнике. */
export const WORK_SOURCE_KEYS = ['work1', 'work2'] as const

export type WorkSourceKey = (typeof WORK_SOURCE_KEYS)[number]

/** Поле в приложении-источнике → вид работы в нашей базе. */
export const WORK_SOURCE_SUBCATEGORY: Record<WorkSourceKey, string> = {
  work1: 'Работа Andrei (инвест)',
  work2: 'Работа Andrei (epam)',
}

/**
 * Название вида работы для поля из приложения-источника.
 *
 * Возвращает null для незнакомого поля, а не «какую-нибудь» работу:
 * если в источнике заведут work3, часы должны остаться незаписанными
 * и заметными, а не тихо приплюсоваться к чужой работе.
 */
export function subcategoryNameForSource(key: string): string | null {
  return isWorkSourceKey(key) ? WORK_SOURCE_SUBCATEGORY[key] : null
}

/** Проверка, что строка — известное поле источника. */
export function isWorkSourceKey(key: string): key is WorkSourceKey {
  return (WORK_SOURCE_KEYS as readonly string[]).includes(key)
}
