import { supabase } from '@/lib/supabase'

/**
 * Автозаполнение будних рабочих дней.
 *
 * Вся работа делается ФУНКЦИЕЙ В БАЗЕ, а не здесь. Причина не в удобстве:
 * записи создаются на имя другого человека, а обычные правила это
 * запрещают — каждый пишет только за себя, и снимать эту защиту ради
 * автозаполнения нельзя. Функция в базе — узкое, описанное исключение:
 * она умеет ровно одно действие и ничего больше.
 *
 * Ещё одно следствие: правило «6 часов инвест, 4 часа epam» живёт
 * в таблице базы, а не в этом файле. Поменяется график — поменяется
 * строка в таблице, без правки кода.
 */

/**
 * Досоздаёт пропущенные будние дни и возвращает, сколько записей появилось.
 *
 * Вызывать можно сколько угодно раз: функция пропускает дни, за которые
 * запись уже есть. Именно поэтому её безопасно звать при каждом открытии
 * приложения, не запоминая, когда заполняли в прошлый раз.
 */
export async function fillWorkdays(): Promise<number> {
  const { data, error } = await supabase.rpc('fill_workdays')

  if (error) throw new Error(error.message)

  // Функция возвращает число; на всякий случай приводим — сбой подсчёта
  // не должен ронять приложение, ради которого всё и делается.
  return typeof data === 'number' ? data : 0
}
