/**
 * Цвета графиков.
 *
 * Это не «подобранные на глаз» цвета. Порядок слотов проверен
 * валидатором палитры на четыре вещи сразу:
 *   - различимость при дальтонизме (ΔE 9.1 при худшей паре);
 *   - различимость обычным зрением (ΔE 22.9);
 *   - диапазон светлоты и насыщенности.
 *
 * ВАЖНО: цвета назначаются по ПОРЯДКУ и никогда не «прокручиваются
 * по кругу». Пятая категория не получит заново синий — если категорий
 * станет больше, лишние сводятся в «Прочее».
 *
 * Валидатор предупредил, что aqua и yellow имеют контраст ниже 3:1
 * к светлому фону. Правило на этот случай — обязательные видимые
 * подписи значений рядом с цветом. Поэтому у всех наших графиков
 * есть легенда с числами: цвет никогда не единственный носитель смысла.
 */

/** Фон, на котором рисуются графики (bg-slate-50 у Tailwind). */
export const CHART_SURFACE = '#f8fafc'

/** Слоты категориальной палитры — строго в этом порядке. */
export const CATEGORICAL = [
  '#2a78d6', // 1 — синий
  '#eb6834', // 2 — оранжевый
  '#1baf7a', // 3 — бирюзовый
  '#eda100', // 4 — жёлтый
  '#e87ba4', // 5 — маджента
  '#008300', // 6 — зелёный
  '#4a3aa7', // 7 — фиолетовый
  '#e34948', // 8 — красный
] as const

/** Оттенки оформления графика: сетка, оси, подписи. */
export const CHART_INK = {
  grid: '#e1e0d9',
  axis: '#c3c2b7',
  muted: '#898781',
  secondary: '#52514e',
} as const

/**
 * Цвет главной категории.
 * Привязан к slug, а не к позиции в списке: при фильтрации
 * категория сохраняет свой цвет, а не перекрашивается.
 *
 * Новая категория берёт СЛЕДУЮЩИЙ свободный слот и никогда не
 * переиспользует занятый. Пятёрка проверена валидатором заново:
 * худшая соседняя пара при дальтонизме ΔE 9.1, обычным зрением 19.6 —
 * обе выше порога.
 */
export const CATEGORY_COLORS: Record<string, string> = {
  work: CATEGORICAL[0],
  study: CATEGORICAL[1],
  household: CATEGORICAL[2],
  childcare: CATEGORICAL[3],
  admin: CATEGORICAL[4],
}

/** Цвет по номеру слота — для графиков, где сущности не категории (например, люди). */
export function colorForIndex(index: number): string {
  // Если сущностей больше восьми, повторно цвета НЕ выдаём:
  // возвращаем серый, а вызывающий код сводит хвост в «Прочее».
  return CATEGORICAL[index] ?? CHART_INK.muted
}
