import { useTheme } from './theme'

/**
 * Цвета графиков.
 *
 * Это не «подобранные на глаз» цвета. Каждая палитра прогнана через
 * валидатор, который проверяет сразу пять вещей: полосу светлоты,
 * насыщенность, различимость при дальтонизме, различимость обычным
 * зрением и контраст к фону, на котором лежит график.
 *
 * ПОЧЕМУ ДВЕ ПАЛИТРЫ, А НЕ ОДНА «ПЕРЕВЁРНУТАЯ».
 * Тёмная тема — не светлая наоборот. Те же самые цвета на тёмном фоне
 * теряют насыщенность и сливаются: проверка это показала прямо —
 * первая попытка просто осветлить палитру провалилась по трём пунктам
 * из пяти. Поэтому у каждой темы свои цвета, подобранные под её фон
 * и проверенные отдельно.
 *
 * ВАЖНО: цвета назначаются по ПОРЯДКУ и никогда не «прокручиваются
 * по кругу». Шестая категория не получит заново синий — если категорий
 * станет больше, лишние сводятся в «Прочее».
 */

/** Слоты категориальной палитры — строго в этом порядке. */
const FOREST_CATEGORICAL = [
  '#304a3a', // 1 — хвоя в тени
  '#66706a', // 2 — камень
  '#c6a15b', // 3 — золото мэллорна
  '#9b4935', // 4 — обожжённая глина
  '#29282a', // 5 — чернила
] as const

/*
 * ПАЛИТРА ВЫБРАНА ВЛАДЕЛЬЦЕМ, А НЕ ВАЛИДАТОРОМ — и это осознанно.
 *
 * Валидатор отклонил её по двум пунктам: «камень» и «чернила» читаются
 * как серые (насыщенность ниже порога), а «хвоя» и «чернила» темнее
 * нижней границы светлоты.
 *
 * Но ГЛАВНУЮ проверку — различимость — набор прошёл: 15.4 обычным
 * зрением при пороге 15 и 14.6 при дальтонизме при пороге 8. Сектора
 * отличить можно, и это то, ради чего проверки существуют. Оставшиеся
 * замечания — про настроение: приглушённость здесь намеренная, под
 * пергамент и старую книгу.
 *
 * Два следствия, с которыми мы согласились сознательно:
 *   — «чернила» почти чёрные и на светлом фоне читаются как тушь;
 *   — у «золота» контраст к фону 2.35 при норме 3, поэтому его край
 *     еле виден. Это допустимо только потому, что у диаграммы есть
 *     легенда с названиями и числами: цвет никогда не единственный
 *     носитель смысла.
 *
 * В ночной теме палитра другая: почти чёрный на тёмном фоне исчез бы.
 */

const MOON_CATEGORICAL = [
  '#6b7f52', // 1 — мох
  '#b7a56a', // 2 — потёртая бронза
  '#65706d', // 3 — камень
  '#4a2925', // 4 — старое дерево
  '#c89b3c', // 5 — латунь фонаря
] as const

/*
 * ⚠ «СТАРОЕ ДЕРЕВО» ПОЧТИ НЕ ВИДНО НА НОЧНОМ ФОНЕ.
 *
 * Контраст #4a2925 к фону — 1.34 при норме 3. Это осознанный выбор
 * владельца, но у него есть цена, и её стоит помнить: слот достаётся
 * категории «Ребёнок», а она обычно самый крупный сектор круга.
 * Большой участок с таким контрастом читается не как цвет, а как
 * пустота в кольце.
 *
 * Работает это только благодаря легенде с названиями и числами рядом:
 * цвет здесь не единственный носитель смысла. Убрать легенду — и
 * диаграмма станет нечитаемой.
 *
 * Если однажды покажется, что в круге дырка, — дело не в поломке,
 * а в этой строке. Осветлить дерево до контраста 3:1 хватит одного
 * значения.
 */

/*
 * ОБЕ ПАЛИТРЫ ВЫБРАНЫ ВЛАДЕЛЬЦЕМ, А НЕ ВАЛИДАТОРОМ.
 *
 * Валидатор отклонил каждую по светлоте и насыщенности: приглушённые
 * землистые цвета он считает «читающимися как серые». Но ГЛАВНУЮ
 * проверку — различимость — обе прошли с запасом. Сектора отличить
 * можно, а приглушённость здесь намеренная: под пергамент в одной
 * теме и под ночную картину в другой.
 */

/** Фон, на котором рисуются графики. Валидатор считает контраст к нему. */
const FOREST_SURFACE = '#fbfcf7'
const MOON_SURFACE = '#171a2e'

/** Оттенки оформления графика: сетка, оси, подписи. */
const FOREST_INK = {
  grid: '#dde2d3',
  axis: '#c2cbb3',
  muted: '#8a9781',
  secondary: '#4d5c46',
} as const

const MOON_INK = {
  grid: '#2b3050',
  axis: '#3d4568',
  muted: '#7a83a6',
  secondary: '#aeb6d4',
} as const

export type ChartPalette = {
  categorical: readonly string[]
  surface: string
  ink: { grid: string; axis: string; muted: string; secondary: string }
  /** Цвет категории по её slug. */
  categoryColors: Record<string, string>
  /** Цвет по номеру слота — для сущностей, которые не категории (людей). */
  colorForIndex: (index: number) => string
}

/**
 * Порядок закрепления цветов за категориями.
 *
 * Цвет привязан к slug, а НЕ к позиции в отфильтрованном списке:
 * иначе, убрав из фильтра «Работу», человек увидел бы, как «Учёба»
 * перекрашивается в её синий, — и решил бы, что смотрит на другие данные.
 */
const CATEGORY_ORDER = ['work', 'study', 'household', 'childcare', 'admin'] as const

function buildPalette(
  categorical: readonly string[],
  surface: string,
  ink: ChartPalette['ink'],
): ChartPalette {
  const categoryColors: Record<string, string> = {}
  CATEGORY_ORDER.forEach((slug, index) => {
    categoryColors[slug] = categorical[index]
  })

  return {
    categorical,
    surface,
    ink,
    categoryColors,
    // Если сущностей больше, чем слотов, повторно цвета НЕ выдаём:
    // возвращаем серый, а вызывающий код сводит хвост в «Прочее».
    colorForIndex: (index: number) => categorical[index] ?? ink.muted,
  }
}

export const FOREST_PALETTE = buildPalette(FOREST_CATEGORICAL, FOREST_SURFACE, FOREST_INK)
export const MOON_PALETTE = buildPalette(MOON_CATEGORICAL, MOON_SURFACE, MOON_INK)

/**
 * Палитра текущей темы.
 *
 * Recharts принимает цвета значениями, а не классами, поэтому взять их
 * из CSS-переменных нельзя — нужен именно такой хук.
 */
export function useChartPalette(): ChartPalette {
  const { isDark } = useTheme()
  return isDark ? MOON_PALETTE : FOREST_PALETTE
}
