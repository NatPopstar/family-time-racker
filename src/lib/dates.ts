/**
 * Работа с датами.
 *
 * В базе поле `date` имеет тип DATE — только год, месяц и день,
 * без времени и без часового пояса. Поэтому в приложении дату
 * тоже возим строкой 'YYYY-MM-DD'.
 */

/**
 * Сегодняшняя дата строкой 'YYYY-MM-DD' ПО МЕСТНОМУ ВРЕМЕНИ.
 *
 * ⚠️ ЛОВУШКА, на которой спотыкаются почти все.
 * Привычное `new Date().toISOString().slice(0, 10)` возвращает дату
 * по Гринвичу, а не по местному времени. Для Лондона летом это значит:
 * всё, что записано после 23:00, попадёт в СЛЕДУЮЩИЙ день. Человек
 * записал уборку вечером понедельника — а она легла во вторник,
 * и недельная статистика поехала.
 *
 * Поэтому собираем строку из местных год/месяц/день вручную.
 */
export function todayISO(date: Date = new Date()): string {
  const year = date.getFullYear()
  // getMonth() считает месяцы с нуля: январь = 0. Поэтому +1.
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

/**
 * День недели даты: 1 — понедельник, 7 — воскресенье.
 *
 * ПОЧЕМУ НЕ getDay() НАПРЯМУЮ. Он считает воскресенье нулём, а неделя
 * у нас начинается с понедельника — так же, как в правилах повтора,
 * где weekday 1 это понедельник. Ноль вместо семёрки означал бы, что
 * правило «каждое воскресенье» никогда не находит своего дня.
 */
export function isoWeekday(isoDate: string): number {
  // 'T00:00:00' обязателен: без него строка читается как время
  // по Гринвичу и вечером может дать соседний день.
  const day = new Date(`${isoDate}T00:00:00`).getDay()
  return day === 0 ? 7 : day
}

/**
 * Показывает дату человеку: '3 сентября' или '3 September'.
 * Год не пишем — в списке за текущую неделю он только мешает.
 */
export function formatDateShort(isoDate: string, locale: 'ru' | 'en'): string {
  // 'T00:00:00' обязателен: без него браузер считает строку 'YYYY-MM-DD'
  // временем по Гринвичу и может показать соседний день.
  const date = new Date(`${isoDate}T00:00:00`)

  return new Intl.DateTimeFormat(locale === 'ru' ? 'ru-RU' : 'en-GB', {
    day: 'numeric',
    month: 'long',
  }).format(date)
}

/**
 * Дата числами: '06/09/26'.
 *
 * Нужна таблицам, где столбец узкий и дат много: «6 сентября» и
 * «31 августа» разной длины, и колонка прыгает. Числа всегда одной
 * ширины, и глаз идёт по столбцу ровно.
 *
 * Разделитель и порядок заданы явно, а не отданы Intl: тот показал бы
 * русскому «06.09.26», а англичанину «06/09/26». В таблице, которую
 * читают оба, дата должна выглядеть одинаково — иначе один и тот же
 * столбец у двух людей разный.
 *
 * Порядок день-месяц-год, а не американский месяц-день: в семье,
 * живущей в Европе, 06/09 — это шестое сентября.
 */
export function formatDateNumeric(isoDate: string): string {
  const [year, month, day] = isoDate.split('-')
  return `${day}/${month}/${year.slice(2)}`
}
