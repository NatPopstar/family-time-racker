import { QueryClient } from '@tanstack/react-query'

/**
 * React Query — «умный посредник» между приложением и базой.
 *
 * Что он берёт на себя вместо нас:
 *   - хранит уже загруженные данные, чтобы не запрашивать их повторно;
 *   - сам даёт признаки «загружается» и «произошла ошибка»;
 *   - сам перезапрашивает данные после того, как мы что-то изменили.
 *
 * Без него в каждом компоненте пришлось бы вручную писать
 * useState + useEffect + loading + error — по 20 строк на каждый список.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // Считать загруженные данные свежими 1 минуту и не дёргать базу зря.
      staleTime: 60_000,
      // Не перезагружать данные каждый раз, когда пользователь
      // переключился на другое окно и вернулся обратно — это раздражает.
      refetchOnWindowFocus: false,
      // Одна повторная попытка при сетевой ошибке вместо трёх по умолчанию:
      // при локальной базе три попытки только затягивают показ ошибки.
      retry: 1,
    },
  },
})
